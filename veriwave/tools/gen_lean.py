"""Extract the Lean embedded in VeriWave's Python into the Lean project (veriwave/lean).

Every module docstring and every function, method and class docstring in vw/ carries a `Lean:` section: the Lean 4
definition that mirrors the Python, its theorems and `#guard` vectors. This tool writes them, in source order, to
lean/VeriWave/<Module>.lean, so `lake build` checks every one. A `#guard` line ends with `-- py: <expression>`, the
same vector in Python; tests/test_fused_lean.py evaluates those.

    python tools/gen_lean.py           write the Lean files
    python tools/gen_lean.py --check   fail if a function has no Lean, or a Lean file is out of date

Standard library only; deterministic output.
"""
from __future__ import annotations

import ast
import os
import sys
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "vw")
OUT = os.path.join(ROOT, "lean", "VeriWave")

# dependency order: each Lean module imports the ones before it
ORDER = ["core", "interfaces", "registry", "router", "verdict", "answer", "codegen", "textgen", "imagegen", "audiogen",
         "videogen", "backends", "store", "factstore", "trace", "evaluate", "querybook", "model", "server"]


def lean_name(mod: str) -> str:
    return "".join(p.capitalize() for p in mod.split("_"))


def lean_section(doc: str | None) -> str | None:
    """the Lean code after the `Lean:` line of a docstring (dedented), or None"""
    if not doc:
        return None
    lines = doc.split("\n")
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped == "Lean:" or (i == 0 and stripped.startswith("Lean:")):
            body = lines[i + 1:]
            if i == 0 and stripped != "Lean:":
                body = [stripped[len("Lean:"):]] + body
            text = textwrap.dedent("\n".join(body)).strip("\n")
            return text if text.strip() else None
    return None


def raw_docstring(src: str, node: ast.AST) -> str | None:
    """the docstring exactly as written in the source (escapes untouched, so the Lean is what Lean will read)"""
    body = getattr(node, "body", None)
    if not body or not isinstance(body[0], ast.Expr) or not isinstance(body[0].value, ast.Constant) \
            or not isinstance(body[0].value.value, str):
        return None
    seg = ast.get_source_segment(src, body[0].value) or ""
    seg = seg.lstrip("rRuUbB")
    for q in ('"""', "'''"):
        if seg.startswith(q) and seg.endswith(q) and len(seg) >= 6:
            return seg[3:-3]
    return seg[1:-1]


def blocks(path: str) -> tuple[str | None, list[tuple[str, int, str | None]]]:
    """(module Lean, [(qualified name, line, Lean or None) for every function, method and class])"""
    with open(path, encoding="utf-8") as f:
        src = f.read()
    tree = ast.parse(src)
    out: list[tuple[str, int, str | None]] = []

    def walk(nodes: list[ast.stmt], prefix: str) -> None:
        for n in nodes:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                out.append((prefix + n.name, n.lineno, lean_section(raw_docstring(src, n))))
                walk(n.body, prefix + n.name + ".")      # methods and nested helpers need Lean too
    walk(tree.body, "")
    return lean_section(raw_docstring(src, tree)), out


def render(mod: str) -> str:
    path = os.path.join(SRC, mod + ".py")
    head, items = blocks(path)
    name = lean_name(mod)
    deps = ORDER[:ORDER.index(mod)]
    parts = ["-- Generated by tools/gen_lean.py from vw/%s.py. Do not edit: change the Python's embedded Lean instead." % mod]
    parts += ["import VeriWave.%s" % lean_name(d) for d in deps]
    parts.append("")
    if deps:
        parts.append("open " + " ".join("VeriWave.%s" % lean_name(d) for d in deps))
        parts.append("")
    parts.append("namespace VeriWave.%s" % name)
    parts.append("")
    if head:
        parts += ["-- module vw/%s.py" % mod, head, ""]
    for qual, line, lean in items:
        if lean:
            parts += ["-- %s (vw/%s.py:%d)" % (qual, mod, line), lean, ""]
    parts.append("end VeriWave.%s" % name)
    return "\n".join(parts) + "\n"


def root_file() -> str:
    return "-- Generated by tools/gen_lean.py. Every VeriWave module's embedded Lean.\n" + "".join(
        "import VeriWave.%s\n" % lean_name(m) for m in ORDER if os.path.isfile(os.path.join(SRC, m + ".py")))


def missing() -> list[str]:
    bad = []
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".py") or fn == "__init__.py":
            continue
        mod = fn[:-3]
        if mod not in ORDER:
            bad.append("vw/%s.py is not in tools/gen_lean.py ORDER" % fn)
            continue
        head, items = blocks(os.path.join(SRC, fn))
        if not head:
            bad.append("vw/%s module docstring has no Lean section" % fn)
        bad += ["vw/%s:%d %s has no Lean section" % (fn, line, qual) for qual, line, lean in items if not lean]
    return bad


def expected() -> dict[str, str]:
    files = {os.path.join(ROOT, "lean", "VeriWave.lean"): root_file()}
    for m in ORDER:
        if os.path.isfile(os.path.join(SRC, m + ".py")):
            files[os.path.join(OUT, lean_name(m) + ".lean")] = render(m)
    return files


def main(argv: list[str]) -> int:
    bad = missing()
    files = expected()
    if "--check" in argv:
        for path, text in files.items():
            try:
                cur = open(path, encoding="utf-8").read()
            except OSError:
                cur = None
            if cur != text:
                bad.append("%s is out of date: run python tools/gen_lean.py" % os.path.relpath(path, ROOT))
        for b in bad:
            print(b)
        return 1 if bad else 0
    os.makedirs(OUT, exist_ok=True)
    for path, text in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    for b in bad:
        print("warning:", b)
    print("wrote %d Lean files" % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
