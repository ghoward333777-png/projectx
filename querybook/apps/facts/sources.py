"""Source rules: every fact rests on sources written by people, never on AI output.

A source is accepted only when its kind is one of HUMAN_KINDS and its web address (if any)
is not an AI chat or AI-writing service. This is a gate on where a claim came from; it does
not make the claim true — conflicting claims are kept side by side and marked disputed.
Also: reading RSS/Atom news feeds (standard library only, on request, with limits).
"""
import html, re, urllib.parse, urllib.request
import xml.etree.ElementTree as ET

HUMAN_KINDS = {
    "book": 0.85, "encyclopedia": 0.85, "reference work": 0.85, "academic journal": 0.9, "government record": 0.9,
    "archive or primary document": 0.95, "museum or library": 0.85, "news agency": 0.75, "newspaper": 0.7,
    "magazine": 0.6, "broadcaster": 0.7, "website (written by people)": 0.5, "eyewitness or interview": 0.6,
    "old QueryBook store (needs checking)": 0.3,
}
KIND_ORDER = list(HUMAN_KINDS)

AI_HOSTS = ("chatgpt.com", "chat.openai.com", "openai.com", "gemini.google.com", "bard.google.com", "claude.ai", "anthropic.com",
            "perplexity.ai", "copilot.microsoft.com", "poe.com", "character.ai", "you.com", "phind.com", "jasper.ai", "writesonic.com",
            "copy.ai", "grok.com", "x.ai", "meta.ai", "deepseek.com", "chat.deepseek.com", "mistral.ai", "chat.mistral.ai", "huggingface.co/chat")


class SourceError(Exception):
    pass


def is_ai_url(url):
    u = urllib.parse.urlsplit((url or "").strip().lower())
    host = (u.hostname or "").lstrip(".")
    path = host + u.path
    for h in AI_HOSTS:
        if "/" in h:
            if path.startswith(h):
                return True
        elif host == h or host.endswith("." + h):
            return True
    return False


def check_source(name, kind, url):
    name = (name or "").strip()
    if not name:
        raise SourceError("Name the source — for example the book title, the newspaper, or the archive.")
    if kind not in HUMAN_KINDS:
        raise SourceError("Choose what kind of source this is (book, newspaper, government record, …).")
    if url:
        u = urllib.parse.urlsplit(url.strip())
        if u.scheme not in ("http", "https") or not u.hostname:
            raise SourceError("The web address must start with http:// or https://")
        if is_ai_url(url):
            raise SourceError("That address belongs to an AI service. This application only accepts sources written by people.")
    if re.search(r"\b(chatgpt|gpt-?\d|claude|gemini|copilot|llm|ai[- ]generated|generated by ai)\b", name, re.I):
        raise SourceError("That source looks like AI output. This application only accepts sources written by people.")
    return HUMAN_KINDS[kind]


# ----------------------------------------------------------------------------- news feeds
MAX_FEED_BYTES = 3_000_000
SUGGESTED_FEEDS = [
    ("BBC News — World", "https://feeds.bbci.co.uk/news/world/rss.xml"),
    ("NPR — News", "https://feeds.npr.org/1001/rss.xml"),
    ("The Guardian — World", "https://www.theguardian.com/world/rss"),
    ("Al Jazeera — All", "https://www.aljazeera.com/xml/rss/all.xml"),
]


def _text(el, *names):
    for n in names:
        for child in el:
            tag = child.tag.split("}")[-1].lower()
            if tag == n:
                if n == "link" and child.get("href"):
                    return child.get("href")
                if child.text and child.text.strip():
                    return child.text.strip()
    return ""


def strip_html(s):
    s = re.sub(r"<[^>]+>", " ", s or "")
    return " ".join(html.unescape(s).split())


def parse_feed(data):
    """RSS 2.0 or Atom bytes -> (feed title, [ {title, link, published, summary} ])."""
    if b"<!ENTITY" in data[:4000].upper():
        raise SourceError("feed refused: it declares XML entities")
    try:
        root = ET.fromstring(data)
    except ET.ParseError as e:
        raise SourceError("the feed is not valid RSS/Atom (%s)" % e)
    items, title = [], ""
    tag = root.tag.split("}")[-1].lower()
    if tag == "rss" or tag == "rdf":
        ch = next((c for c in root if c.tag.split("}")[-1].lower() == "channel"), root)
        title = _text(ch, "title")
        entries = [e for e in root.iter() if e.tag.split("}")[-1].lower() == "item"]
    else:
        title = _text(root, "title")
        entries = [e for e in root if e.tag.split("}")[-1].lower() == "entry"]
    for e in entries[:200]:
        t = strip_html(_text(e, "title"))
        link = _text(e, "link", "guid")
        if not t:
            continue
        items.append({"title": t[:500], "link": link[:1000], "published": _text(e, "pubdate", "published", "updated", "date")[:60],
                      "summary": strip_html(_text(e, "description", "summary", "content"))[:1000]})
    return strip_html(title), items


def fetch_feed(url, timeout=15):
    u = urllib.parse.urlsplit(url or "")
    if u.scheme not in ("http", "https") or not u.hostname:
        raise SourceError("The feed address must start with http:// or https://")
    if is_ai_url(url):
        raise SourceError("That address belongs to an AI service.")
    req = urllib.request.Request(url, headers={"User-Agent": "QueryBook-History-News/1.0 (+local reader)"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            data = r.read(MAX_FEED_BYTES + 1)
    except Exception as e:
        raise SourceError("could not fetch the feed: %s" % e)
    if len(data) > MAX_FEED_BYTES:
        raise SourceError("the feed is larger than 3 MB; refused")
    return parse_feed(data)
