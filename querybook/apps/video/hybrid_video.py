#!/usr/bin/env python3
"""QueryBook hybrid video renderer: reuse what is known, generate only what is missing.

A request names one or more actions in order ("walk-toward, sit-down"), and how the result should look (vertical or
horizontal, speed, colour, length). The renderer:

  1. PLANS   each action against the clip library: a stored clip of the same action (and the same look, if one is asked
             for) is REUSED; only an action with no usable clip is GENERATED. The plan shows each step, why, and its
             estimated seconds — measured from earlier runs — before anything runs.
  2. RENDERS reused clips are retrieved and edited locally (re-crop, speed, colour, trim: seconds); missing actions are
             generated by the video model (minutes) and STORED, so the next request for them is a reuse; several actions
             are joined into one video with short cross-fades.
  3. CHECKS  every segment and the result: length, motion present, and the motion of each reused segment kept
             (its motion curve against the stored clip's). A failed generation is not stored.
  4. RECORDS what each step really took (the planner's estimates learn from it) and returns the video with its report.

The library is a folder: <library>/<action>/<clip>.mp4 + index.json (action, look, source, consent, checks, timings).
Clips come from generation (the model and prompt are recorded) or from filmed footage added with the performer's
consent note. Generation uses the admin's Gemini key and the SHARED daily budget of the answer-video tool.

    python tools/hybrid_video.py plan    --library DIR --actions walk-toward,sit-down --format vertical
    python tools/hybrid_video.py render  --library DIR --actions walk-toward,sit-down --format vertical --out clip.mp4 \\
                                         [--key-file gemini-key.json --budget-folder <answer-video library>]
    python tools/hybrid_video.py add     --library DIR --action open-bottle --file my.mp4 --consent "filmed with Sam's signed release"
    python tools/hybrid_video.py import-bench --library DIR --bench <reuse_bench folder>
    python tools/hybrid_video.py self-test
"""
import hashlib, json, os, shutil, statistics, subprocess, sys, tempfile, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import reuse_bench as rb  # noqa: E402  (ffmpeg helpers, motion curves, the action prompts)
import qbframes as qf  # noqa: E402  (frame interpolation and upscaling: AI programs when installed, ffmpeg otherwise)

MODEL = rb.MODEL
DEFAULT_GEN_S = 120.0               # until a generation has been timed here
FORMATS = {"horizontal": (1280, 720), "vertical": (720, 1280), "square": (1080, 1080)}
GRADES = {"none": None, "warm": "eq=brightness=0.04:saturation=1.25,colorbalance=rs=0.08:bs=-0.06",
          "cool": "eq=saturation=1.1,colorbalance=rs=-0.05:bs=0.08", "mono": "hue=s=0"}
PROMPTS = dict(rb.ACTIONS)
MIN_MOTION = 0.25          # mean frame difference: a still picture measures ~0; small hand work (scrolling a phone) ~0.4


def _now():
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


class Library:
    def __init__(self, folder):
        self.folder = os.path.abspath(folder)
        os.makedirs(self.folder, exist_ok=True)
        self.path = os.path.join(self.folder, "index.json")
        try:
            self.data = json.load(open(self.path, encoding="utf-8"))
        except (OSError, ValueError):
            self.data = {"clips": [], "timings": {}}

    def save(self):
        tmp = self.path + ".tmp"
        json.dump(self.data, open(tmp, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        os.replace(tmp, self.path)

    def add(self, action, src, source, consent=None, look="", prompt=None, gen_seconds=None):
        os.makedirs(os.path.join(self.folder, action), exist_ok=True)
        h = hashlib.sha256(open(src, "rb").read()).hexdigest()[:16]
        dst = os.path.join(self.folder, action, h + ".mp4")
        if not os.path.exists(dst):
            shutil.copyfile(src, dst)
        curve = rb.motion_curve(dst)
        entry = {"id": h, "action": action, "file": os.path.relpath(dst, self.folder), "look": look or "", "source": source,
                 "consent": consent, "prompt": prompt, "added": _now(), "duration_s": round(rb.duration(dst), 2),
                 "motion": round(statistics.fmean(curve), 2) if curve else 0.0, "generation_seconds": gen_seconds}
        self.data["clips"] = [c for c in self.data["clips"] if c["id"] != h] + [entry]
        self.save()
        return entry

    def find(self, action, look=""):
        """the best stored clip of an action: same look first, then the one with the clearest motion"""
        cands = [c for c in self.data["clips"] if c["action"] == action and c.get("motion", 0) >= MIN_MOTION]
        if look:
            same = [c for c in cands if c.get("look", "").lower() == look.lower()]
            return (same and max(same, key=lambda c: c["motion"])) or None
        return max(cands, key=lambda c: c["motion"]) if cands else None

    def timing(self, step):
        t = self.data["timings"].get(step) or []
        return statistics.median(t) if t else None

    def record(self, step, seconds):
        self.data["timings"].setdefault(step, []).append(round(seconds, 3))
        self.data["timings"][step] = self.data["timings"][step][-50:]


# ------------------------------------------------------------------------------------------------ plan
def plan(lib, actions, fmt="horizontal", speed=1.0, grade="none", max_seconds=None, look="", fps_out=None, height=None,
         interp="best", bridges=True):
    """the cheapest route for each action, with its reason and estimated seconds (measured medians where known)"""
    if fmt not in FORMATS:
        raise ValueError("format must be one of %s" % ", ".join(FORMATS))
    if grade not in GRADES:
        raise ValueError("grade must be one of %s" % ", ".join(GRADES))
    steps = []
    gen_est = lib.timing("generate") or DEFAULT_GEN_S
    edit_est = lib.timing("edit") or 1.5
    for a in actions:
        c = lib.find(a, look)
        if c:
            steps.append({"action": a, "route": "reuse", "clip": c["id"], "source": c["source"],
                          "why": "a stored clip of this action%s" % (" with the same look" if look else ""),
                          "estimate_s": round(edit_est, 1)})
        elif a in PROMPTS or look:
            steps.append({"action": a, "route": "generate", "why": "no stored clip of this action%s — generated once, then stored for reuse"
                          % (" with that look" if look else ""), "estimate_s": round(gen_est, 1)})
        else:
            steps.append({"action": a, "route": "missing", "why": "no stored clip and no prompt for this action: add footage or a prompt",
                          "estimate_s": None})
    join = len(actions) > 1
    total = sum(s["estimate_s"] or 0 for s in steps) + ((lib.timing("join") or 2.0) if join else 0)
    # the extra frame work, costed per second of output from earlier runs (defaults: measured on 4 CPU cores, 720p)
    seconds_out = sum((next((c["duration_s"] for c in lib.data["clips"] if c["id"] == st.get("clip")), 8.0) if st["route"] == "reuse" else 8.0)
                      for st in steps) / (speed or 1.0)
    if max_seconds:
        seconds_out = min(seconds_out, max_seconds * len(actions) / (speed or 1.0))
    extras = []
    be = qf.backends()
    smooth_slow = speed < 1.0 and interp == "best"
    if smooth_slow or fps_out:
        per = lib.timing("interp_per_s") or (1.0 if "RIFE" in be["interpolation"] else 14.0)
        extras.append({"step": "interpolate", "why": ("smooth slow motion" if smooth_slow else "") + (" and " if smooth_slow and fps_out else "") +
                       ("%s frames per second" % fps_out if fps_out else ""), "backend": be["interpolation"], "estimate_s": round(per * seconds_out, 1)})
    if join and bridges:
        extras.append({"step": "bridge joins", "why": "in-between frames at each join when the clips' ends are similar (else a cross-fade)",
                       "backend": be["interpolation"], "estimate_s": round((lib.timing("bridge") or (1.0 if "RIFE" in be["interpolation"] else 8.0)) * (len(actions) - 1), 1)})
    if height:
        per = lib.timing("upscale_per_s") or (1.0 if "ESRGAN" in be["upscaling"] else 2.0)
        extras.append({"step": "upscale", "why": "to %d pixels high" % height, "backend": be["upscaling"], "estimate_s": round(per * seconds_out, 1)})
    total += sum(e["estimate_s"] for e in extras)
    all_gen = len(actions) * gen_est
    return {"actions": actions, "format": fmt, "speed": speed, "grade": grade, "max_seconds": max_seconds, "look": look,
            "fps": fps_out, "height": height, "interp": interp, "steps": steps, "frame_work": extras, "backends": be,
            "join": join, "estimate_s": round(total, 1),
            "estimate_all_generated_s": round(all_gen, 1),
            "reused": sum(1 for s in steps if s["route"] == "reuse"), "generated": sum(1 for s in steps if s["route"] == "generate")}


# ------------------------------------------------------------------------------------------------ render
def _edit(src, dst, fmt, speed, grade, max_seconds):
    w, h = FORMATS[fmt]
    vf = []
    if speed and abs(speed - 1.0) > 1e-6:                  # change the speed first, then fix the frame rate (even frame spacing)
        vf.append("setpts=%f*PTS" % (1.0 / speed))
    vf += ["scale=%d:%d:force_original_aspect_ratio=increase" % (w, h), "crop=%d:%d" % (w, h), "fps=24"]
    if GRADES[grade]:
        vf.append(GRADES[grade])
    args = ["-i", src, "-vf", ",".join(vf), "-an", "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p"]
    if max_seconds:
        args += ["-t", str(max_seconds)]
    rb._ff(args + [dst])


def _join(parts, dst, fade=0.4):
    """segments into one video with short cross-fades (all segments share size and frame rate after _edit)"""
    if len(parts) == 1:
        shutil.copyfile(parts[0], dst)
        return [{"join": 0, "how": "single segment"}]
    durs = [rb.duration(p) for p in parts]
    inputs, fc, prev, off = [], [], "[0:v]", 0.0
    for p in parts:
        inputs += ["-i", p]
    for i in range(1, len(parts)):
        off += durs[i - 1] - fade
        out = "[v%d]" % i
        fc.append("%s[%d:v]xfade=transition=fade:duration=%s:offset=%.3f%s" % (prev, i, fade, max(0.0, off), out))
        prev = out
    rb._ff(inputs + ["-filter_complex", ";".join(fc), "-map", prev, "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p", dst])
    return [{"join": i, "how": "cross-fade"} for i in range(1, len(parts))]


def _concat(paths, dst):
    inputs, ins = [], ""
    for i, p in enumerate(paths):
        inputs += ["-i", p]
        ins += "[%d:v]" % i
    rb._ff(inputs + ["-filter_complex", "%sconcat=n=%d:v=1[v]" % (ins, len(paths)), "-map", "[v]", "-c:v", "libx264", "-preset", "veryfast",
                     "-pix_fmt", "yuv420p", dst])


def _join_bridged(parts, dst, tmp, lib):
    """each join: in-between frames when the clips' ends are similar, a cross-fade when they are not"""
    joins, cur = [], parts[0]
    for i, nxt in enumerate(parts[1:], 1):
        t0 = time.time()
        br = os.path.join(tmp, "bridge-%02d.mp4" % i)
        backend, diff = qf.bridge(cur, nxt, br)
        out = os.path.join(tmp, "join-%02d.mp4" % i)
        if backend:
            _concat([cur, br, nxt], out)
            joins.append({"join": i, "how": "bridged with in-between frames", "backend": backend, "difference": diff,
                          "seconds": round(time.time() - t0, 2)})
            lib.record("bridge", time.time() - t0)
        else:
            _join([cur, nxt], out)
            joins.append({"join": i, "how": "cross-fade (the ends differ too much for in-between frames)", "difference": diff,
                          "seconds": round(time.time() - t0, 2)})
        cur = out
    shutil.copyfile(cur, dst)
    return joins


def render(lib, actions, out, fmt="horizontal", speed=1.0, grade="none", max_seconds=None, look="", generator=None,
           fps_out=None, height=None, interp="best", bridges=True):
    """carry out the plan; generator(action, prompt) -> mp4 bytes is called only for actions with no usable clip"""
    p = plan(lib, actions, fmt, speed, grade, max_seconds, look, fps_out, height, interp, bridges)
    smooth_slow = speed < 1.0 and interp == "best"
    t_all = time.time()
    tmp = tempfile.mkdtemp(prefix="qb-hybrid-")
    report = {"plan": p, "steps": [], "started": _now()}
    try:
        parts = []
        for st in p["steps"]:
            a, row = st["action"], {"action": st["action"], "route": st["route"]}
            if st["route"] == "missing":
                raise ValueError(st["why"] + " (%s)" % a)
            if st["route"] == "generate":
                if generator is None:
                    raise ValueError("'%s' must be generated, and no generator is set up (give --key-file)" % a)
                prompt = (PROMPTS.get(a) or a.replace("-", " ")) + (" The person: %s." % look if look else "") + " " + rb.STYLE
                t0 = time.time()
                data = generator(a, prompt)
                gsec = time.time() - t0
                raw = os.path.join(tmp, a + "-generated.mp4")
                open(raw, "wb").write(data)
                curve = rb.motion_curve(raw)
                okm = curve and statistics.fmean(curve) >= MIN_MOTION and rb.duration(raw) >= 2.0
                row.update(generate_s=round(gsec, 1), checks={"duration_s": round(rb.duration(raw), 2), "motion_present": bool(okm)})
                if not okm:
                    raise RuntimeError("the generated clip for '%s' failed its checks (too short or no motion): not stored" % a)
                c = lib.add(a, raw, "generated by %s" % MODEL, consent="no real person: text prompt only", look=look, prompt=prompt, gen_seconds=round(gsec, 1))
                lib.record("generate", gsec)
                row["stored_as"] = c["id"]
            else:
                c = next(x for x in lib.data["clips"] if x["id"] == st["clip"])
            src = os.path.join(lib.folder, c["file"])
            t0 = time.time()
            seg = os.path.join(tmp, "%02d-%s.mp4" % (len(parts), a))
            _edit(src, seg, fmt, 1.0 if smooth_slow else speed, grade, max_seconds)
            esec = time.time() - t0
            lib.record("edit", esec)
            if smooth_slow:                               # slow motion with new in-between frames, not repeated ones
                t1 = time.time()
                slow = os.path.join(tmp, "%02d-%s-slow.mp4" % (len(parts), a))
                row["interpolation"] = qf.interpolate(seg, slow, slow=speed)
                lib.record("interp_per_s", (time.time() - t1) / max(0.1, rb.duration(slow)))
                seg = slow
            ref = rb.motion_curve(src)
            kept = rb._corr(rb.motion_curve(seg), rb._resample(ref, speed) if speed != 1.0 else ref)   # slower = the curve stretched
            row.update(edit_s=round(esec, 2), clip=c["id"], motion_kept=round(kept, 3),
                       ok=kept >= (0.6 if max_seconds else 0.75) and rb.duration(seg) > 0.5)
            report["steps"].append(row)
            parts.append(seg)
        t0 = time.time()
        joined = os.path.join(tmp, "joined.mp4")
        report["joins"] = _join_bridged(parts, joined, tmp, lib) if (bridges and len(parts) > 1) else _join(parts, joined)
        if len(parts) > 1:
            lib.record("join", time.time() - t0)
        cur = joined
        if fps_out:
            t1 = time.time()
            nxt = os.path.join(tmp, "fps.mp4")
            report["fps_backend"] = qf.interpolate(cur, nxt, target_fps=fps_out, mode=interp)
            if report["fps_backend"] != "frame duplication":
                lib.record("interp_per_s", (time.time() - t1) / max(0.1, rb.duration(nxt)))
            cur = nxt
        if height:
            t1 = time.time()
            nxt = os.path.join(tmp, "up.mp4")
            report["upscale_backend"] = qf.upscale(cur, nxt, height)
            lib.record("upscale_per_s", (time.time() - t1) / max(0.1, rb.duration(nxt)))
            report["upscale_ssim"] = round(qf.ssim(cur, nxt), 4)       # the upscaled video still matches its source
            cur = nxt
        shutil.copyfile(cur, out)
        total = time.time() - t_all
        w_, h_ = qf.size(out)
        report.update(total_s=round(total, 2), output=os.path.abspath(out), duration_s=round(rb.duration(out), 2),
                      size="%dx%d" % (w_, h_), fps=round(qf.fps(out), 2),
                      ok=all(s.get("ok") for s in report["steps"]) and (not height or report.get("upscale_ssim", 0) >= 0.85)
                      and (not fps_out or abs(qf.fps(out) - fps_out) < 0.5), finished=_now(),
                      compared_with_all_generated_s=p["estimate_all_generated_s"])
        lib.record("request", total)
        lib.save()
        return report
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def gemini_generator(key_file, budget_folder):
    import generate_exemplars as ge
    key = json.load(open(key_file))["api_key"] if key_file.endswith(".json") else open(key_file).read().strip()
    budget = ge.Budget(type("L", (), {"folder": budget_folder})())

    def gen(action, prompt):
        if not budget.reserve(MODEL):
            raise RuntimeError("no %s requests left today (shared with the answer videos); stored clips still work" % MODEL)
        try:
            data, _ext = ge.generate(key, MODEL, prompt)
            return data
        except Exception as e:
            if "429" in str(e) or "RESOURCE_EXHAUSTED" in str(e):
                budget.refund(MODEL)
            raise
    return gen


def import_bench(lib, bench_folder):
    b = rb.Bench(bench_folder)
    n = 0
    for k, a in b.data["actions"].items():
        if a.get("stored"):
            lib.add(k, b.clip(k, a["stored"]), "generated by %s" % a.get("model", MODEL), consent="no real person: text prompt only",
                    prompt=a.get("prompt"), gen_seconds=a.get("scratch_seconds"))
            if a.get("scratch_seconds"):
                lib.record("generate", a["scratch_seconds"])
            n += 1
    lib.save()
    return n


