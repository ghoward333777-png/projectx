#!/usr/bin/env python3
"""Generate the Rust port's formula functions and the shared test vectors from the Python code.

  rust/qbcore/src/formulas.rs       one function per solution of every STEM formula (apps/stem/science.py)
  rust/qbcore/vectors/qbmath.tsv    exact outputs of apps/_core/qbmath.py (network memory, answer routing)
  rust/qbcore/vectors/formulas.tsv  results of the STEM application's own evaluator for sample inputs

    python tools/gen_rust.py          write the files
    python tools/gen_rust.py --check  exit 1 if the committed files differ from what the Python code generates
"""
from __future__ import annotations

import ast
import os
import sys
from fractions import Fraction

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "apps", "stem"))
sys.path.insert(0, os.path.join(ROOT, "apps", "_core"))
import engine  # noqa: E402
import qbmath  # noqa: E402
import science  # noqa: E402

CRATE = os.path.join(ROOT, "rust", "qbcore")


def flit(text: str) -> str:
    v = float(Fraction(text))
    s = repr(v)
    return (s if ("." in s or "e" in s or "inf" in s) else s + ".0") + "_f64"


def to_rust(expr: str, consts: dict[str, str]) -> str:
    def go(n: ast.AST) -> str:
        if isinstance(n, ast.Expression):
            return go(n.body)
        if isinstance(n, ast.Constant):
            return flit(str(n.value))
        if isinstance(n, ast.Name):
            if n.id == "pi":
                return "PI"
            if n.id in consts:
                return flit(consts[n.id])
            return n.id
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            return "(-%s)" % go(n.operand)
        if isinstance(n, ast.BinOp):
            if isinstance(n.op, ast.Pow):
                if isinstance(n.right, ast.Constant) and float(n.right.value).is_integer():
                    return "(%s).powi(%d)" % (go(n.left), int(n.right.value))
                return "(%s).powf(%s)" % (go(n.left), go(n.right))
            sym = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/"}[type(n.op)]
            return "(%s %s %s)" % (go(n.left), sym, go(n.right))
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Name):
            a = ", ".join(go(x) for x in n.args)
            return {"sqrt": "(%s).sqrt()", "ln": "(%s).ln()", "sind": "sind(%s)", "asind": "asind(%s)"}[n.func.id] % a
        raise ValueError(ast.dump(n))

    return go(ast.parse(expr, mode="eval"))


def formulas_rs() -> str:
    out = ["// GENERATED by tools/gen_rust.py from apps/stem/science.py — do not edit by hand.",
           "// One function per solution of every STEM formula; arguments in the formula's own variable order.",
           "#![allow(non_snake_case, unused_parens, clippy::all)]",
           "use std::f64::consts::PI;",
           "",
           "/// sine of an angle in degrees (STEM's sind)",
           "pub fn sind(x: f64) -> f64 { (x * PI / 180.0).sin() }",
           "/// arcsine in degrees (STEM's asind)",
           "pub fn asind(y: f64) -> f64 { y.asin() * 180.0 / PI }",
           ""]
    table = []
    for fid, name, field, disp, vars_, sol, consts in science.FORMULAS:
        names = [v for v, _, _, _ in vars_]
        out.append("// %s: %s" % (name, disp))
        for x in names:
            if x not in sol:
                continue
            args = [v for v in names if v != x]
            out.append("pub fn %s_%s(%s) -> f64 { %s }" % (fid, x, ", ".join("%s: f64" % a for a in args), to_rust(sol[x], consts)))
            table.append((fid, x, args))
        out.append("")
    out.append("/// Call a solution by name with arguments in order (used by the test vectors).")
    out.append("pub fn call(name: &str, a: &[f64]) -> Option<f64> {")
    out.append("    Some(match name {")
    for fid, x, args in table:
        out.append('        "%s_%s" => %s_%s(%s),' % (fid, x, fid, x, ", ".join("a[%d]" % i for i in range(len(args)))))
    out.append("        _ => return None,")
    out.append("    })")
    out.append("}")
    return "\n".join(out) + "\n"


SAMPLE = {"theta": "30", "t1": "30", "t2": "20", "rate": "0.05", "n": "12", "t": "10", "strain": "0.002", "eta": "0.8"}


def sample_inputs(fid: str, x: str, names: list[str]) -> dict[str, Fraction]:
    vals = {v: Fraction(SAMPLE.get(v, str(2 + i))) for i, v in enumerate(names)}
    if fid == "parallel":
        vals.update({"R": Fraction(2), "R1": Fraction(3), "R2": Fraction(6)})
    if fid == "suvat2":
        vals.update({"v": Fraction(10), "u": Fraction(4), "a": Fraction(2), "s": Fraction(21)})
    if fid == "pythagoras":
        vals.update({"a": Fraction(3), "b": Fraction(4), "c": Fraction(5)})
    if fid == "projectile":
        vals.update({"v": Fraction(20), "g": Fraction("9.80665"), "Rg": Fraction(30)})
    if fid == "snell":
        vals.update({"n1": Fraction("1.0"), "n2": Fraction("1.33")})
    if fid == "interest":
        vals.update({"P": Fraction(1000), "Amt": Fraction(1500)})
    if fid == "efficiency":
        vals.update({"eta": Fraction("0.8"), "Pout": Fraction(80), "Pin": Fraction(100)})
    return vals


def formulas_tsv() -> str:
    lines = ["# name\targs (comma-separated, Python repr)\texpected (Python repr) — computed by apps/stem/engine.evaluate_with"]
    for fid, name, field, disp, vars_, sol, consts in science.FORMULAS:
        names = [v for v, _, _, _ in vars_]
        for x in names:
            if x not in sol:
                continue
            vals = sample_inputs(fid, x, names)
            env = {k: v for k, v in vals.items() if k != x}
            env.update({k: Fraction(v) for k, v in consts.items()})
            r = engine.evaluate_with(sol[x], env)
            args = [v for v in names if v != x]
            lines.append("%s_%s\t%s\t%r" % (fid, x, ",".join(repr(float(vals[a])) for a in args), float(r)))
    return "\n".join(lines) + "\n"


def qbmath_tsv() -> str:
    grid = [0.0, 0.0001, 0.05, 0.1, 0.2, 0.28, 0.3, 0.33333, 0.4999, 0.5, 0.6, 0.7777, 0.95, 0.9999, 1.0]
    lines = ["# function\targs\texpected (Python repr) — computed by apps/_core/qbmath.py"]
    for s in grid:
        lines.append("syn_potentiate\t%r\t%r" % (s, qbmath.syn_potentiate(s)))
        lines.append("syn_depress\t%r\t%r" % (s, qbmath.syn_depress(s)))
        lines.append("dsn_hit\t%r\t%r" % (s, qbmath.dsn_hit(s)))
        lines.append("dsn_miss\t%r\t%r" % (s, qbmath.dsn_miss(s)))
        lines.append("dsn_recover\t%r\t%r" % (s, qbmath.dsn_recover(s)))
        for days in (0.0, 0.5, 1.0, 3.0, 10.0, 33.3):
            for cons in (False, True):
                lines.append("syn_fade\t%r,%r,%d\t%r" % (s, days, int(cons), qbmath.syn_fade(s, days, cons)))
    for good in range(0, 25, 3):
        for bad in range(0, 9, 2):
            lines.append("syn_threshold\t%d,%d\t%r" % (good, bad, qbmath.syn_threshold(good, bad)))
            lines.append("syn_consolidated\t%d,%d\t%d" % (good, bad, int(qbmath.syn_consolidated(good, bad))))
    return "\n".join(lines) + "\n"


FILES = {os.path.join("src", "formulas.rs"): formulas_rs, os.path.join("vectors", "formulas.tsv"): formulas_tsv,
         os.path.join("vectors", "qbmath.tsv"): qbmath_tsv}

if __name__ == "__main__":
    check, bad = "--check" in sys.argv, []
    for rel, fn in FILES.items():
        text, path = fn(), os.path.join(CRATE, rel)
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    bad += [] if f.read() == text else [rel]
            except OSError:
                bad.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if bad:
        print("Out of date (run tools/gen_rust.py):", ", ".join(bad))
        sys.exit(1)
